const localizeWorkMedia = (project, language) => {
  const images = (project.images || []).filter(item => !item.language || item.language === language);
  return { ...project, images };
};

export function translateSiteContent(content, language) {
  const localizedWorkProjects = (content.work.projects || []).map(project => localizeWorkMedia(project, language));
  if (language !== 'es') {
    return {
      ...content,
      work: { ...content.work, projects: localizedWorkProjects }
    };
  }

  return {
    ...content,
    global: {
      ...content.global,
      ...spanishGlobal,
      workMenuLabel: content.global.workMenuLabelEs || spanishGlobal.workMenuLabel,
      exhibitionsMenuLabel: content.global.exhibitionsMenuLabelEs || spanishGlobal.exhibitionsMenuLabel,
      statementMenuLabel: content.global.statementMenuLabelEs || spanishGlobal.statementMenuLabel,
      contactMenuLabel: content.global.contactMenuLabelEs || spanishGlobal.contactMenuLabel,
      cvMenuLabel: content.global.cvMenuLabelEs || spanishGlobal.cvMenuLabel,
      workshopsMenuLabel: content.global.workshopsMenuLabelEs || spanishGlobal.workshopsMenuLabel
    },
    home: {
      ...content.home,
      heroImageAlt: 'Instalación de Andrea Alkalay en Soulangh Cultural Park',
      selectedWorkLabel: 'obra seleccionada',
      viewWorkLabel: 'Ver obra',
      viewMoreLabel: 'Ver más'
    },
    work: {
      ...content.work,
      projects: localizedWorkProjects.map(project => ({
        ...project,
        title: spanishWorkTitles[project.slug] || project.title,
        intro: project.introEs?.trim() || workStatementsEs[project.slug] || project.intro,
        images: (project.images || []).map(translateArtwork)
      }))
    },
    exhibitions: {
      ...content.exhibitions,
      projects: (content.exhibitions.projects || []).map(project => ({
        ...project,
        title: project.title,
        intro: project.introEs?.trim() || exhibitionStatementsEs[project.slug] || project.intro,
        images: (project.images || []).map(translateArtwork)
      }))
    },
    statement: {
      ...content.statement,
      imageAlt: 'Retrato de Andrea Alkalay',
      title: 'Statement',
      paragraphs: content.statement.paragraphsEs?.length
        ? content.statement.paragraphsEs
        : content.statement.paragraphs
    },
    about: { ...content.about, ...spanishAbout },
    contact: {
      ...content.contact,
      imageAlt: 'Detalle de una exposición de Andrea Alkalay',
      title: 'Conversemos.',
      subtitle: 'Exhibiciones, colaboraciones y prensa.',
      links: (content.contact.links || []).map(link => ({
        ...link,
        label: link.label === 'Email' ? 'Correo electrónico' : link.label
      }))
    },
    cv: {
      ...content.cv,
      introLabel: '',
      intro: content.cv.introEs?.trim() || translateCvText(content.cv.intro),
      sections: (content.cv.sections || []).map(section => ({
        ...section,
        title: translateCvText(section.title),
        items: (section.items || []).map(item => typeof item === 'string'
          ? translateCvText(item)
          : { ...item, title: translateCvText(item.title) })
      }))
    },
    workshops: {
      ...content.workshops,
      title: content.workshops.titleEs || content.workshops.title,
      rows: (content.workshops.rows || []).map(row => ({
        ...row,
        title: row.titleEs || row.title,
        imageAlt: row.imageAltEs || row.imageAlt,
        text: row.textEs || row.text
      }))
    }
  };
}
